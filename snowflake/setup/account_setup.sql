USE ROLE ACCOUNTADMIN;
 
CREATE RESOURCE MONITOR IF NOT EXISTS RM_RETAIL_POC
  WITH CREDIT_QUOTA = 60
  FREQUENCY = MONTHLY
  START_TIMESTAMP = IMMEDIATELY
  TRIGGERS
    ON 50  PERCENT DO NOTIFY
    ON 75  PERCENT DO NOTIFY
    ON 90  PERCENT DO SUSPEND
    ON 100 PERCENT DO SUSPEND_IMMEDIATE; 
 
ALTER WAREHOUSE COMPUTE_WH SET
  WAREHOUSE_SIZE = 'XSMALL'
  AUTO_SUSPEND   = 60
  AUTO_RESUME    = TRUE
  RESOURCE_MONITOR = RM_RETAIL_POC;


USE ROLE SECURITYADMIN;
 
CREATE ROLE IF NOT EXISTS LOADER_ROLE;
CREATE ROLE IF NOT EXISTS TRANSFORMER_ROLE;
CREATE ROLE IF NOT EXISTS REPORTER_ROLE;
 
GRANT ROLE LOADER_ROLE      TO ROLE SYSADMIN;
GRANT ROLE TRANSFORMER_ROLE TO ROLE SYSADMIN;
GRANT ROLE REPORTER_ROLE    TO ROLE SYSADMIN;
 

SET my_user = CURRENT_USER();
GRANT ROLE LOADER_ROLE      TO USER IDENTIFIER($my_user);
GRANT ROLE TRANSFORMER_ROLE TO USER IDENTIFIER($my_user);
GRANT ROLE REPORTER_ROLE    TO USER IDENTIFIER($my_user);


