USE ROLE SYSADMIN;
USE WAREHOUSE COMPUTE_WH;
 
CREATE OR REPLACE STAGE RETAIL_DB.BRONZE.STG_S3_LANDING
  URL = 's3://<BUCKET_NAME>/'
  CREDENTIALS = (AWS_KEY_ID = '<ACCESS_KEY_ID>' AWS_SECRET_KEY = '<SECRET_ACCESS_KEY>')
  FILE_FORMAT = RETAIL_DB.BRONZE.FF_CSV
  COMMENT = 'S3 landing bucket (access-key fallback): customers/, orders/, order_items/';
 
-- CREATE OR REPLACE drops existing grants, so reapply them
GRANT USAGE ON STAGE RETAIL_DB.BRONZE.STG_S3_LANDING TO ROLE LOADER_ROLE;
GRANT CREATE PROCEDURE, CREATE TASK ON SCHEMA RETAIL_DB.BRONZE TO ROLE LOADER_ROLE;
 
USE ROLE ACCOUNTADMIN;
GRANT EXECUTE TASK ON ACCOUNT TO ROLE LOADER_ROLE;
 
LIST @RETAIL_DB.BRONZE.STG_S3_LANDING;   -- 0 rows on an empty bucket = authenticated
