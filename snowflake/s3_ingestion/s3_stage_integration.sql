
USE ROLE ACCOUNTADMIN;

CREATE STORAGE INTEGRATION IF NOT EXISTS RETAIL_S3_INT
  TYPE = EXTERNAL_STAGE
  STORAGE_PROVIDER = 'S3'
  ENABLED = TRUE
  STORAGE_AWS_ROLE_ARN = 'arn:aws:iam::<AWS_ACCOUNT_ID>:role/snowflake-retail-s3-role'
  STORAGE_ALLOWED_LOCATIONS = ('s3://<BUCKET_NAME>/');

-- Copy these two values into the role's trust policy in AWS:
--   STORAGE_AWS_IAM_USER_ARN  -> Principal.AWS
--   STORAGE_AWS_EXTERNAL_ID   -> Condition sts:ExternalId
DESC STORAGE INTEGRATION RETAIL_S3_INT;

-- SYSADMIN creates the stage, so it needs to use the integration
GRANT USAGE ON INTEGRATION RETAIL_S3_INT TO ROLE SYSADMIN;


-- 2. External stage  (SYSADMIN, after the AWS trust policy is updated)

USE ROLE SYSADMIN;
USE WAREHOUSE COMPUTE_WH;
USE SCHEMA RETAIL_DB.BRONZE;

CREATE STAGE IF NOT EXISTS STG_S3_LANDING
  STORAGE_INTEGRATION = RETAIL_S3_INT
  URL = 's3://<BUCKET_NAME>/'
  FILE_FORMAT = RETAIL_DB.BRONZE.FF_CSV
  COMMENT = 'S3 landing bucket: customers/, orders/, order_items/';

LIST @STG_S3_LANDING;

-- 3. Grants for the loader  (it owns the S3 load procedure and task
GRANT USAGE ON STAGE STG_S3_LANDING TO ROLE LOADER_ROLE;   -- external stages use USAGE
GRANT CREATE PROCEDURE, CREATE TASK ON SCHEMA RETAIL_DB.BRONZE TO ROLE LOADER_ROLE;

USE ROLE ACCOUNTADMIN;
GRANT EXECUTE TASK ON ACCOUNT TO ROLE LOADER_ROLE;
