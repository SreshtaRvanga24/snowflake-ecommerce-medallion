
USE ROLE SYSADMIN;
USE WAREHOUSE COMPUTE_WH;
USE SCHEMA RETAIL_DB.BRONZE;


-- File format

CREATE FILE FORMAT IF NOT EXISTS FF_CSV
  TYPE = CSV
  FIELD_OPTIONALLY_ENCLOSED_BY = '"'
  SKIP_HEADER = 1
  NULL_IF = ('', 'NULL', 'null')
  EMPTY_FIELD_AS_NULL = TRUE
  TRIM_SPACE = TRUE
  ERROR_ON_COLUMN_COUNT_MISMATCH = TRUE;


-- Internal stage: Airflow downloads from Azurite and PUTs files here. 
CREATE STAGE IF NOT EXISTS STG_AZURE_INTERNAL
  FILE_FORMAT = FF_CSV
  COMMENT = 'Landing area for files pulled from Azure Blob (Azurite) by Airflow';

-- Bronze tables Source columns in CSV order, then the same lineage columns on every table.
   
CREATE TABLE IF NOT EXISTS CUSTOMERS (
  CUSTOMER_ID     VARCHAR,
  CUSTOMER_NAME   VARCHAR,
  EMAIL           VARCHAR,
  REGION          VARCHAR,
  CITY            VARCHAR,
  SEGMENT         VARCHAR,
  SIGNUP_DATE     VARCHAR,
  IS_ACTIVE       VARCHAR,
  UPDATED_AT      VARCHAR,
  -- lineage
  SOURCE_SYSTEM              VARCHAR,
  SOURCE_FILE_NAME           VARCHAR,
  SOURCE_FILE_ROW_NUMBER     NUMBER,
  SOURCE_FILE_LAST_MODIFIED  TIMESTAMP_NTZ,
  LOAD_ID                    VARCHAR,
  INGESTION_TIMESTAMP        TIMESTAMP_LTZ DEFAULT CURRENT_TIMESTAMP()
);

CREATE TABLE IF NOT EXISTS ORDERS (
  ORDER_ID        VARCHAR,
  CUSTOMER_ID     VARCHAR,
  ORDER_DATE      VARCHAR,
  ORDER_TS        VARCHAR,
  ORDER_STATUS    VARCHAR,
  SALES_CHANNEL   VARCHAR,
  SUBTOTAL        VARCHAR,
  DISCOUNT_AMOUNT VARCHAR,
  ORDER_AMOUNT    VARCHAR,
  CURRENCY        VARCHAR,
  UPDATED_AT      VARCHAR,
  -- lineage
  SOURCE_SYSTEM              VARCHAR,
  SOURCE_FILE_NAME           VARCHAR,
  SOURCE_FILE_ROW_NUMBER     NUMBER,
  SOURCE_FILE_LAST_MODIFIED  TIMESTAMP_NTZ,
  LOAD_ID                    VARCHAR,
  INGESTION_TIMESTAMP        TIMESTAMP_LTZ DEFAULT CURRENT_TIMESTAMP()
);

CREATE TABLE IF NOT EXISTS ORDER_ITEMS (
  ORDER_ITEM_ID   VARCHAR,
  ORDER_ID        VARCHAR,
  PRODUCT_ID      VARCHAR,
  PRODUCT_NAME    VARCHAR,
  CATEGORY        VARCHAR,
  QUANTITY        VARCHAR,
  UNIT_PRICE      VARCHAR,
  LINE_AMOUNT     VARCHAR,
  UPDATED_AT      VARCHAR,
  -- lineage
  SOURCE_SYSTEM              VARCHAR,
  SOURCE_FILE_NAME           VARCHAR,
  SOURCE_FILE_ROW_NUMBER     NUMBER,
  SOURCE_FILE_LAST_MODIFIED  TIMESTAMP_NTZ,
  LOAD_ID                    VARCHAR,
  INGESTION_TIMESTAMP        TIMESTAMP_LTZ DEFAULT CURRENT_TIMESTAMP()
);

CREATE TABLE IF NOT EXISTS PAYMENTS (
  PAYMENT_ID      VARCHAR,
  ORDER_ID        VARCHAR,
  CUSTOMER_ID     VARCHAR,
  PAYMENT_TS      VARCHAR,
  PAYMENT_METHOD  VARCHAR,
  PAYMENT_STATUS  VARCHAR,
  AMOUNT          VARCHAR,
  CURRENCY        VARCHAR,
  UPDATED_AT      VARCHAR,
  -- lineage
  SOURCE_SYSTEM              VARCHAR,
  SOURCE_FILE_NAME           VARCHAR,
  SOURCE_FILE_ROW_NUMBER     NUMBER,
  SOURCE_FILE_LAST_MODIFIED  TIMESTAMP_NTZ,
  LOAD_ID                    VARCHAR,
  INGESTION_TIMESTAMP        TIMESTAMP_LTZ DEFAULT CURRENT_TIMESTAMP()
);

CREATE TABLE IF NOT EXISTS ORDER_STATUS_EVENTS (
  EVENT_ID        VARCHAR,
  ORDER_ID        VARCHAR,
  STATUS          VARCHAR,
  EVENT_TS        VARCHAR,
  SOURCE_SYSTEM_CODE VARCHAR,   -- CSV column SOURCE_SYSTEM (WEB, ...); renamed so it
                                -- doesn't clash with the lineage column below
  UPDATED_AT      VARCHAR,
  -- lineage
  SOURCE_SYSTEM              VARCHAR,
  SOURCE_FILE_NAME           VARCHAR,
  SOURCE_FILE_ROW_NUMBER     NUMBER,
  SOURCE_FILE_LAST_MODIFIED  TIMESTAMP_NTZ,
  LOAD_ID                    VARCHAR,
  INGESTION_TIMESTAMP        TIMESTAMP_LTZ DEFAULT CURRENT_TIMESTAMP()
);

-- Existing tables need the grants too (future grants only cover new ones)
GRANT SELECT, INSERT ON ALL TABLES IN SCHEMA RETAIL_DB.BRONZE TO ROLE LOADER_ROLE;
GRANT SELECT         ON ALL TABLES IN SCHEMA RETAIL_DB.BRONZE TO ROLE TRANSFORMER_ROLE;
GRANT READ, WRITE ON STAGE STG_AZURE_INTERNAL TO ROLE LOADER_ROLE;
GRANT USAGE       ON FILE FORMAT FF_CSV       TO ROLE LOADER_ROLE;

SHOW TABLES IN SCHEMA RETAIL_DB.BRONZE;

