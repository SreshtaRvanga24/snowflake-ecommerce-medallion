USE ROLE ACCOUNTADMIN;
USE WAREHOUSE COMPUTE_WH;
USE SCHEMA RETAIL_DB.AUDIT;
 
-- One row per file per load attempt (written by Airflow and from COPY_HISTORY)
CREATE TABLE IF NOT EXISTS FILE_INGESTION_LOG (
  LOAD_ID             VARCHAR       NOT NULL,   
  SOURCE_SYSTEM       VARCHAR       NOT NULL,   
  SOURCE_FILE_NAME    VARCHAR       NOT NULL,
  TARGET_TABLE        VARCHAR       NOT NULL,
  STATUS              VARCHAR       NOT NULL,  
  ROWS_PARSED         NUMBER,
  ROWS_LOADED         NUMBER,
  ERRORS_SEEN         NUMBER,
  FIRST_ERROR_MESSAGE VARCHAR,
  STARTED_AT          TIMESTAMP_LTZ DEFAULT CURRENT_TIMESTAMP(),
  FINISHED_AT         TIMESTAMP_LTZ
);
 
-- One row per data-quality check result (fed from dbt run_results.json)
CREATE TABLE IF NOT EXISTS DATA_QUALITY_RESULTS (
  RUN_ID          VARCHAR       NOT NULL,
  CHECK_NAME      VARCHAR       NOT NULL,
  MODEL_NAME      VARCHAR,
  STATUS          VARCHAR       NOT NULL,   
  FAILED_ROWS     NUMBER,
  MESSAGE         VARCHAR,
  CHECKED_AT      TIMESTAMP_LTZ DEFAULT CURRENT_TIMESTAMP()
);
 
-- One row per Gold task run (fed from INFORMATION_SCHEMA.TASK_HISTORY)
CREATE TABLE IF NOT EXISTS GOLD_PROCESSING_LOG (
  TASK_NAME       VARCHAR       NOT NULL,
  TARGET_OBJECT   VARCHAR,
  STATE           VARCHAR       NOT NULL,   -- SUCCEEDED / FAILED / SKIPPED
  ROWS_INSERTED   NUMBER,
  ROWS_UPDATED    NUMBER,
  ERROR_MESSAGE   VARCHAR,
  SCHEDULED_AT    TIMESTAMP_LTZ,
  COMPLETED_AT    TIMESTAMP_LTZ
);
 
-- Existing tables need the grants too (future grants only cover new ones)
GRANT SELECT, INSERT, UPDATE ON ALL TABLES IN SCHEMA RETAIL_DB.AUDIT TO ROLE LOADER_ROLE;
GRANT SELECT, INSERT, UPDATE ON ALL TABLES IN SCHEMA RETAIL_DB.AUDIT TO ROLE TRANSFORMER_ROLE;
 
